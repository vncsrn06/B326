package com.joysistvi.stage1.day8;

public class DoWhileStatement {
    public static void main(String[] args) {


        // [Syntax] Do-While Loop

    /*
    Initialization;
    do {
    statement / body of the loop
    increment / decrement
    } while (condition);
     */

        int i = 1;
        do {
            System.out.println(i);
            i++;
        } while (i <= 10);
    }
}

